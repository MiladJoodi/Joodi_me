export function getChartEntry(id: string) {
  return chartsCatalog.find((item) => item.id === id)
}

export function getChartsByCategory(category: string) {
  return chartsCatalog.filter((item) => item.category === category)
}

export function isChartCategory(value: string): value is ChartCategory {
  return (CHART_CATEGORIES as readonly string[]).includes(value)
}

export function chartViewHref(id: string) {
  return `/charts/view/${id}`
}

export function chartCategoryHref(category: string) {
  return `/charts/${category}`
}
